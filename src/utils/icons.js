/**
 * Returns SVG markup for a given icon name or legacy emoji.
 * @param {string} name - Icon name key or legacy emoji string
 * @param {Object} [options] - Options: size (number/string), color, className
 * @returns {string} - Rendered SVG markup
 */
export function getCustomIcon(name, options = {}) {
  if (!name) return ICONS_MAP.dumbbell;

  // Resolve legacy emoji if passed
  const resolvedKey = EMOJI_TO_ICON_MAP[name] || name;
  let svg = ICONS_MAP[resolvedKey] || ICONS_MAP.dumbbell;

  const { size, color, className } = options;

  if (size || color || className) {
    const sizeAttr = size ? `width="${size}" height="${size}"` : '';
    const colorStyle = color ? `style="color: ${color};"` : '';
    const classAttr = className ? `class="custom-svg-icon ${className}"` : '';

    svg = svg
      .replace(/width="[^"]*"/, sizeAttr ? sizeAttr.split(' ')[0] : 'width="24"')
      .replace(/height="[^"]*"/, sizeAttr ? sizeAttr.split(' ')[1] : 'height="24"');

    if (colorStyle) {
      svg = svg.replace('<svg', `<svg ${colorStyle}`);
    }
    if (className) {
      svg = svg.replace('class="custom-svg-icon"', classAttr);
    }
  }

  return svg;
}

/**
 * Star icon for favorite toggles. Both ⭐ (favorited) and ☆ (not) used to map
 * to the same outline star glyph, which loses the on/off distinction those
 * two emoji carried — so this fills the star and tints it gold when active,
 * instead of just swapping in the one shape both states would otherwise share.
 */
export function getFavoriteIcon(isFav) {
  const svg = ICONS_MAP.star;
  if (isFav) {
    return svg
      .replace('fill="none"', 'fill="currentColor"')
      .replace('<svg', '<svg style="color:#ffd60a;"');
  }
  return svg.replace('<svg', '<svg style="color:var(--text-muted);"');
}

/**
 * Helper to get custom icon by exercise category
 */
export function getCategoryIcon(category) {
  if (!category) return ICONS_MAP.dumbbell;
  const c = category.toLowerCase();
  if (c.includes('חזה') || c.includes('chest')) return ICONS_MAP.chest;
  if (c.includes('גב') || c.includes('back')) return ICONS_MAP.back;
  if (c.includes('רגליים') || c.includes('legs')) return ICONS_MAP.legs;
  if (c.includes('כתפיים') || c.includes('shoulders')) return ICONS_MAP.shoulders;
  if (c.includes('ידיים') || c.includes('arms') || c.includes('יד')) return ICONS_MAP.arms;
  if (c.includes('בטן') || c.includes('core')) return ICONS_MAP.core;
  if (c.includes('אירובי') || c.includes('cardio') || c.includes('ריצה')) return ICONS_MAP.cardio;
  return ICONS_MAP.dumbbell;
}

/**
 * Helper to get custom icon by location
 */
export function getLocationIcon(location) {
  if (!location) return ICONS_MAP.gym;
  const l = location.toLowerCase();
  if (l.includes('park') || l.includes('פארק') || l.includes('בחוץ')) return ICONS_MAP.park;
  if (l.includes('outdoor') || l.includes('שטח')) return ICONS_MAP.outdoor;
  return ICONS_MAP.gym;
}
